#include <iostream>
// Подключение библиотеки для работы с динамическими массивами (vector)
#include <vector>
// Подключение библиотеки для работы со строками (string)
#include <string>
// Подключение библиотеки для хеш-таблицы (unordered_map) — словарь "ключ → значение"
#include <unordered_map>

// Структура для описания товара (используется как вспомогательный тип данных)
struct Product {
    std::string name;   // Название товара
    int quantity;       // Количество единиц товара
};

// Класс "Склад" — хранит название и список товаров с их количеством
class Warehouse {
public:
    std::string name;   // Название склада

    // Хеш-таблица: ключ — название товара (string), значение — количество (int)
    // Позволяет быстро находить товар по имени за O(1) в среднем
    std::unordered_map<std::string, int> inventory;

    // Конструктор: принимает название склада и инициализирует поле name
    // const std::string& — передача по константной ссылке, без копирования
    Warehouse(const std::string& n) : name(n) {}

    // Метод добавления товара на склад
    // Если товар уже есть — увеличивает количество, если нет — создаёт новую запись
    void addProduct(const std::string& productName, int qty) {
        inventory[productName] += qty;  // operator[] создаёт запись с 0 если её нет, затем прибавляет qty
    }

    // Метод удаления (списания) товара со склада
    // Возвращает true если операция успешна, false если товара недостаточно или он отсутствует
    bool removeProduct(const std::string& productName, int qty) {
        // Ищем товар в хеш-таблице, получаем итератор
        auto it = inventory.find(productName);

        // Проверяем: товар найден И его количество не меньше запрошенного
        if (it != inventory.end() && it->second >= qty) {
            it->second -= qty;  // Уменьшаем количество товара на qty

            // Если количество стало 0 — удаляем запись из таблицы (чистим память)
            if (it->second == 0) {
                inventory.erase(it);  // Удаление элемента по итератору
            }
            return true;    // Операция выполнена успешно
        }
        return false;   // Товар не найден или недостаточно единиц
    }

    // Метод вывода содержимого склада в консоль
    // const — гарантия что метод не изменяет состояние объекта
    void display() const {
        std::cout << "Склад: " << name << "\n";    // Выводим название склада

        // Проверяем пустой ли склад
        if (inventory.empty()) {
            std::cout << "Пусто\n";
        } else {
            // Перебираем все пары (название товара, количество) в хеш-таблице
            // const auto& item — константная ссылка на пару, без копирования
            for (const auto& item : inventory) {
                // item.first — название товара, item.second — количество
                std::cout << "  " << item.first << ": " << item.second << "\n";
            }
        }
    }
};

// Класс "Приложение логистики" — управляет всеми складами и обрабатывает команды пользователя
class LogisticsApp {
private:
    // Динамический массив складов — хранит все созданные склады
    std::vector<Warehouse> warehouses;

public:
    // Главный метод запуска приложения — основной цикл работы программы
    void run() {
        int choice; // Переменная для хранения выбора пользователя

        // Цикл do-while: выполняется хотя бы один раз, продолжается пока choice != 0
        do {
            showMenu();         // Выводим меню в консоль
            std::cin >> choice; // Считываем выбор пользователя

            // Обрабатываем выбор через switch
            switch(choice) {
                case 1:
                    createWarehouse();          // Создать новый склад
                    break;
                case 2:
                    addProductToWarehouse();    // Добавить товар на склад
                    break;
                case 3:
                    transferProduct();          // Переместить товар между складами
                    break;
                case 4:
                    showAllWarehouses();        // Показать все склады и их содержимое
                    break;
                case 0:
                    std::cout << "Выход...\n"; // Сообщение перед завершением
                    break;
                default:
                    std::cout << "Неверный выбор.\n"; // Обработка некорректного ввода
            }
        } while (choice != 0); // Выходим из цикла когда пользователь ввёл 0
    }

private:
    // Метод вывода главного меню в консоль
    void showMenu() {
        std::cout << "\n--- Меню ---\n";
        std::cout << "1. Создать склад\n";
        std::cout << "2. Добавить товар\n";
        std::cout << "3. Переместить товар\n";
        std::cout << "4. Показать все склады\n";
        std::cout << "0. Выйти\n";
        std::cout << "Ваш выбор: ";
    }

    // Метод создания нового склада
    void createWarehouse() {
        std::cout << "Введите название склада: ";
        std::string name;       // Локальная переменная для имени склада
        std::cin >> name;       // Считываем название с консоли

        // emplace_back — создаёт объект Warehouse прямо внутри вектора,
        // эффективнее чем push_back (нет лишнего копирования)
        warehouses.emplace_back(name);
        std::cout << "Склад создан!\n";
    }

    // Вспомогательный метод: предлагает пользователю выбрать склад из списка
    // Возвращает указатель на выбранный склад или nullptr при ошибке
    Warehouse* selectWarehouse() {
        // Проверяем что хотя бы один склад существует
        if (warehouses.empty()) {
            std::cout << "Нет созданных складов.\n";
            return nullptr; // nullptr — нулевой указатель, обозначает "ничего не выбрано"
        }

        std::cout << "Выберите склад:\n";

        // Выводим пронумерованный список складов
        // size_t — беззнаковый целочисленный тип для размеров и индексов
        for (size_t i = 0; i < warehouses.size(); ++i) {
            std::cout << i+1 << ". " << warehouses[i].name << "\n"; // Нумерация с 1 для удобства пользователя
        }

        int idx;        // Индекс выбранного склада (вводится пользователем)
        std::cin >> idx;

        // Проверяем корректность введённого индекса
        // (int)warehouses.size() — приведение size_t к int для корректного сравнения
        if (idx < 1 || idx > (int)warehouses.size()) {
            std::cout << "Некорректный выбор.\n";
            return nullptr;
        }

        // Возвращаем указатель на элемент вектора по индексу (idx-1 т.к. пользователь нумерует с 1)
        return &warehouses[idx-1];
    }

    // Метод добавления товара на выбранный склад
    void addProductToWarehouse() {
        Warehouse* wh = selectWarehouse(); // Просим пользователя выбрать склад
        if (!wh) return;    // Если склад не выбран (nullptr) — выходим из метода

        std::cout << "Введите название товара: ";
        std::string productName;    // Название товара
        std::cin >> productName;

        std::cout << "Введите количество: ";
        int qty;            // Количество единиц товара
        std::cin >> qty;

        // Валидация: количество должно быть положительным
        if (qty <= 0) {
            std::cout << "Некорректное количество.\n";
            return;
        }

        wh->addProduct(productName, qty);   // Вызов метода добавления через указатель
        std::cout << "Товар добавлен.\n";
    }

    // Метод перемещения товара между двумя складами
    void transferProduct() {
        std::cout << "Выберите склад-отправитель:\n";
        Warehouse* fromWh = selectWarehouse();  // Указатель на склад-источник
        if (!fromWh) return;

        std::cout << "Выберите склад-получатель:\n";
        Warehouse* toWh = selectWarehouse();    // Указатель на склад-назначение

        // Проверяем: склад выбран И это не тот же самый склад (перевод самому себе бессмысленен)
        if (!toWh || toWh == fromWh) {
            std::cout << "Некорректный выбор склада.\n";
            return;
        }

        std::cout << "Введите название товара: ";
        std::string productName;
        std::cin >> productName;

        std::cout << "Введите количество: ";
        int qty;
        std::cin >> qty;

        // Валидация количества
        if (qty <= 0) {
            std::cout << "Некорректное количество.\n";
            return;
        }

        // Пытаемся списать товар со склада-отправителя
        // removeProduct возвращает true если товара достаточно
        if (fromWh->removeProduct(productName, qty)) {
            toWh->addProduct(productName, qty); // Зачисляем товар на склад-получатель
            std::cout << "Перевод выполнен.\n";
        } else {
            // Товара недостаточно — отменяем операцию (ничего не меняем)
            std::cout << "Недостаточно товара на складе-отправителе.\n";
        }
    }

    // Метод вывода всех складов и их содержимого
    void showAllWarehouses() {
        if (warehouses.empty()) {
            std::cout << "Нет складов.\n";
            return;
        }

        // Перебираем все склады и вызываем их метод display()
        // const auto& wh — константная ссылка, без копирования объекта
        for (const auto& wh : warehouses) {
            wh.display();   // Каждый склад сам знает как отобразить своё содержимое
        }
    }
};


int main() {
    LogisticsApp app;   // Создаём объект приложения (вызывается конструктор по умолчанию)
    app.run();          // Запускаем основной цикл работы приложения
    return 0;           // Возвращаем 0 — стандартный код успешного завершения программы
}
